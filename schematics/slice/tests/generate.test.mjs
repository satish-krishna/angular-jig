describe('novel specs (no golden file; type-checked for real by verify-arrives-green)', () => {
  const NOVEL = ['gadget', 'ticket', 'shipment', 'status-note'];
  const novel = (name) => readFileSync(join(SLICE_DIR, 'fixtures', 'novel', `${name}.json`), 'utf8');

  it.each(NOVEL)('%s is a valid spec and generates the same bytes twice', (name) => {
    const parsed = parseSpec(JSON.parse(novel(name)));
    expect(parsed.ok, parsed.errors?.join('; ')).toBe(true);
    const a = [...generateFiles(parsed.spec).entries()];
    const b = [...generateFiles(parseSpec(JSON.parse(novel(name))).spec).entries()];
    expect(a.length).toBeGreaterThan(0);
    expect(b).toEqual(a);
  });

  it('together they cover the shapes the reviewer asked for', () => {
    const specs = NOVEL.map((n) => parseSpec(JSON.parse(novel(n))).spec);
    expect(specs.some((s) => s.manage?.createRoute)).toBe(true);
    const fields = specs.flatMap((s) => s.fields);
    for (const type of ['string', 'text', 'number', 'boolean', 'enum', 'date', 'ref']) {
      expect(fields.some((f) => f.type === type && f.required === false) || type === 'number' || type === 'boolean' || type === 'enum').toBe(true);
    }
    expect(specs.some((s) => s.kinds.length === 1 && s.kinds[0] === 'entity')).toBe(true);
    expect(specs.some((s) => !s.kinds.includes('manage'))).toBe(true);
    const selects = specs.flatMap((s) => (s.manage?.filters ?? []).filter((f) => f.control === 'select').map((f) => [s, f]));
    expect(selects.some(([s, f]) => { const x = s.fields.find((y) => y.name === f.field); return x.type === 'enum' && x.inForm === false; })).toBe(true);
    const toggles = specs.flatMap((s) => (s.manage?.filters ?? []).filter((f) => f.control === 'toggle').map((f) => [s, f]));
    expect(toggles.some(([s, f]) => s.fields.find((x) => x.name === f.field).type === 'boolean')).toBe(true);
    expect(toggles.some(([, f]) => f.value !== undefined)).toBe(true);
    expect(fields.some((f) => f.type === 'ref' && !f.many)).toBe(true);
    expect(fields.some((f) => f.type === 'ref' && f.many)).toBe(true);
    expect(fields.some((f) => f.type === 'number' && f.min === undefined && f.max === undefined)).toBe(true);
  });
});

