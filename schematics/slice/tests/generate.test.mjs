describe('what the generated code may and may not contain', () => {
  /** Every free-text string in a spec: labels, placeholders, help, options, example strings, button text. */
  function specStrings(spec) {
    // labels.singular and labels.plural are left out: they often equal the entity identifier, which
    // legitimately appears in selectors and test ids. They reach templates only through vm.text.
    const strings = new Set();
    for (const f of spec.fields) {
      strings.add(f.label);
      if (f.placeholder) strings.add(f.placeholder);
      if (f.help) strings.add(f.help);
      for (const o of f.options ?? []) strings.add(o);
    }
    if (spec.manage) {
      strings.add(spec.manage.createLabel);
      for (const flt of spec.manage.filters ?? []) if (flt.label) strings.add(flt.label);
    }
    for (const row of spec.examples ?? []) {
      for (const v of Object.values(row)) if (typeof v === 'string' && v.length > 3) strings.add(v);
    }
    return [...strings].filter((s) => s.length > 2);
  }

  /** The text of every Angular template in a generated file: the .html itself, or inline `template:` bodies. */
  function templatesOf(path, content) {
    if (path.endsWith('.html')) return [content];
    const sf = ts.createSourceFile(path, content, ts.ScriptTarget.Latest, true);
    const found = [];
    const visit = (node) => {
      if (ts.isPropertyAssignment(node) && node.name.getText(sf) === 'template' && ts.isNoSubstitutionTemplateLiteral(node.initializer)) {
        found.push(node.initializer.text);
      }
      ts.forEachChild(node, visit);
    };
    visit(sf);
    return found;
  }

  it.each(FIXTURES)('%s: no spec text appears inside any template, only bindings to constants', async (name) => {
    const spec = parseSpec(JSON.parse(readFixture(name))).spec;
    const strings = specStrings(spec);
    for (const [path, content] of await generateFixture(name)) {
      for (const template of templatesOf(path, content)) {
        for (const s of strings) expect(template.includes(s), `${path} pastes "${s}" into markup`).toBe(false);
      }
    }
  });

  it.each(FIXTURES)('%s: every generated TypeScript file parses and every template compiles', async (name) => {
    for (const [path, content] of await generateFixture(name)) {
      if (path.endsWith('.ts')) {
        const result = ts.transpileModule(content, { reportDiagnostics: true, compilerOptions: { target: ts.ScriptTarget.ES2022 } });
        expect(result.diagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n')), path).toEqual([]);
      }
      for (const template of templatesOf(path, content)) {
        expect(parseTemplate(template, path).errors ?? [], path).toEqual([]);
      }
    }
  });

  it('survives awkward-but-allowed text: quotes, apostrophes, ampersands, percent, at-signs', async () => {
    const data = JSON.parse(readFixture('loan'));
    data.labels = { singular: `agent's "loan" & more`, plural: `agents' "loans" @ 50%` };
    data.fields[0].label = `Dr. Ion's "Code" & Name; 100% #1 @home`;
    data.fields[0].placeholder = `It's "fine" & 'quoted'`;
    data.fields[2].options[4] = `Don't "stop"`;
    for (const row of data.examples) if (row.status === 'Lost') row.status = `Don't "stop"`;
    data.examples[0].reference = `It's "quoted" & done`;
    data.manage.createLabel = `Log it's "new" & more`;
    data.manage.filters.push({ field: 'status', control: 'select' });
    const filtered = data.fields.find((f) => f.name === 'status');
    filtered.label = `Dr. Ion's "Code" & 100%`;
    data.manage.sort = { field: filtered.name, direction: 'asc' };
    const parsed = parseSpec(data);
    expect(parsed.ok, parsed.errors?.join('\n')).toBe(true);
    const files = generateFiles(parsed.spec);
    for (const [path, content] of files) {
      if (path.endsWith('.ts')) {
        const result = ts.transpileModule(content, { reportDiagnostics: true, compilerOptions: { target: ts.ScriptTarget.ES2022 } });
        expect(result.diagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n')), path).toEqual([]);
      }
      for (const template of templatesOf(path, content)) {
        expect(parseTemplate(template, path).errors ?? [], path).toEqual([]);
        expect(template.includes('quoted'), path).toBe(false);
        expect(template.includes('Dr. Ion'), path).toBe(false);
      }
    }
    expect(files.get('src/app/loan/loan-example-data.ts')).toContain(JSON.stringify(`It's "quoted" & done`));
  });
});

