// Two-letter portrait fallback from the first letters of the first two words: "Dr. Ion" -> "DI".
export function heroInitials(name: string): string {
  return name
    .split(/\s+/)
    .filter((word) => /^[A-Za-z]/.test(word))
    .slice(0, 2)
    .map((word) => word[0].toUpperCase())
    .join('');
}
